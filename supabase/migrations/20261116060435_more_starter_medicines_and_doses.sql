-- What this is: many more starter medicines for the medicine list, each with
-- its strength, and more doses in milligrams for the dose picker.
--
-- Why: Anthony, 2026-11-16 (request 196b): "The pharmacy drugs, you have to
-- add them, the starter list, all of it... Make sure you add the milligram
-- for picker... Then the dosage as well."
--   - The list follows the medicines usual in a Nigerian hospital (the
--     Nigeria Essential Medicines List), with their usual strengths, written
--     from general knowledge. The Pharmacy checks it, like the first starter
--     list: each line is standard, marked "starter" until confirmed.
--   - The milligram is picked, because each strength is its own line.
--
-- Must never:
--   - Change or remove a line already on the list. "on conflict do nothing"
--     skips any medicine and strength that is already there, so a line the
--     Pharmacy added or confirmed stays exactly as it is.
--   - Touch anything but these two lists. It only adds rows, and moves the
--     starter line "As directed" to the end of the dose list.
-- =============================================================================


